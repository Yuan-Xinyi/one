"""How fast does the vertex-valued resolution have to switch?

The relaxation theorem says that trajectories generated by vertex-valued
commands are dense in those generated by box-valued commands, so restricting
the action space to the vertices of the command box is not a restriction in the
continuous-time limit -- provided the switching can be fast enough. At a finite
control rate that proviso is an empirical question, and this measures it: how
often the selected vertex actually changes, and how long the resolution dwells
on one vertex before leaving it.

A low switching rate means the control rate is comfortably above what the task
needs, and the relaxation argument applies with room to spare. A rate close to
one switch per step means the control rate is the binding resource, which would
be worth reporting in its own right.

Curvature is the reason to measure this per task family rather than once. A
bend makes the constraint that ends the episode move while the arm is tracking
it, so if anything is going to exhaust the switching budget it is the sharpest
waves; the swing-angle buckets are there to show whether it does.

Usage:
    python -m Yuan.IJRR.eval.switching_rate --n-tasks 1024
    python -m Yuan.IJRR.eval.switching_rate \
        --config Yuan/IJRR/stage2_traj/config_vertex.yaml \
        --ckpt Yuan/IJRR/runs/rl_vertex_30M --swing-max-deg 30
"""
from __future__ import annotations

import argparse
import dataclasses
import math
from pathlib import Path

import numpy as np
import torch
import yaml

from Yuan.IJRR.env.env import NSRLBatchedEnv, EnvConfig
from Yuan.IJRR.env.line_distribution import (
    LineDistribution, ScriptedLineDistribution)
from Yuan.IJRR.stage2_traj.ppo import Agent

REPO = Path(__file__).resolve().parents[3]


@torch.no_grad()
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ckpt', default='Yuan/RL_controller/runs/rl_smmstart_30M')
    ap.add_argument('--config', default='Yuan/IJRR/stage2_traj/config.yaml')
    ap.add_argument('--n-tasks', type=int, default=1024)
    ap.add_argument('--seed', type=int, default=4242)
    ap.add_argument('--swing-max-deg', type=float, default=-1.0,
                    help='-1 keeps the config value; 0 forces straight tasks')
    ap.add_argument('--observe-curvature', type=int, default=-1,
                    help='-1 keeps the config value; 0/1 overrides it, so a '
                         '31-D line-trained policy can be measured on curves')
    ap.add_argument('--device', default='cuda')
    a = ap.parse_args()

    dev = torch.device(a.device)
    y = yaml.safe_load(open(REPO / a.config))
    keys = {f.name for f in dataclasses.fields(EnvConfig)}
    kw = {k: v for k, v in y['env'].items() if k in keys}
    line_cfg = dict(y['line_distribution'])
    if a.observe_curvature >= 0:
        kw['observe_curvature'] = bool(a.observe_curvature)
    if a.swing_max_deg >= 0.0:
        line_cfg['swing_max_deg'] = a.swing_max_deg
    swing_max = float(line_cfg.get('swing_max_deg', 0.0))
    N = a.n_tasks

    env = NSRLBatchedEnv(EnvConfig(**{**kw, 'n_envs': N}), None, dev)
    pool = LineDistribution.load_or_build(
        kin=env.kin, collision=env.collision, n_pool=max(3 * N, 20000),
        n_target_noise_deg=line_cfg['n_target_noise_deg'], seed=a.seed,
        env_cfg=env.cfg,
        feasibility_threshold_m=line_cfg['feasibility_threshold_m'],
        swing_max_deg=swing_max,
        wavelen_range=tuple(line_cfg.get('wavelen_range', (0.4, 1.2))),
        min_radius_m=line_cfg.get('min_radius_m', 0.15), verbose=False)
    idx = torch.nonzero(pool.valid_mask, as_tuple=False).squeeze(-1)[:N]
    env.line_dist = ScriptedLineDistribution(
        {'q0': pool.q_pool[idx], 'line_dir': pool.line_dir_pool[idx],
         'n_target': pool.n_target_pool[idx],
         'amp': pool.amp_pool[idx], 'wavelen': pool.wavelen_pool[idx]})

    ck = torch.load(REPO / a.ckpt / 'agent.pt', map_location=dev,
                    weights_only=False)
    sd = ck['agent'] if isinstance(ck, dict) and 'agent' in ck else ck
    if any(k.startswith('_logits_head') for k in sd):
        from Yuan.IJRR.stage2_traj.vertex_agent import VertexAgent
        ag = VertexAgent(obs_dim=env.obs_dim, act_dim=env.act_dim,
                         hidden_dim=512).to(dev)
    else:
        ag = Agent(obs_dim=env.obs_dim, act_dim=env.act_dim,
                   hidden_dim=512).to(dev)
    ag.load_state_dict(sd); ag.eval()

    env.reset()
    prev = None
    flips = torch.zeros(N, env.act_dim, device=dev)  # per-coord sign changes
    vswitch = torch.zeros(N, device=dev)       # changes of the whole vertex
    steps = torch.zeros(N, device=dev)
    dwell_cur = torch.zeros(N, device=dev)
    dwells = []
    done = torch.zeros(N, dtype=torch.bool, device=dev)
    for _ in range(env.max_steps):
        s = torch.sign(ag.actor_mean(env.current_obs()))
        s = torch.where(s == 0, torch.ones_like(s), s)
        live = ~done
        if prev is not None:
            ch = (s != prev) & live.unsqueeze(-1)
            flips += ch.float()
            vs = ch.any(-1)
            vswitch += vs.float()
            ended = vs & live
            if ended.any():
                dwells.append(dwell_cur[ended].clone())
            dwell_cur = torch.where(vs, torch.zeros_like(dwell_cur),
                                    dwell_cur + live.float())
        else:
            dwell_cur = live.float()
        steps += live.float()
        prev = s
        env.step(ag.actor_mean(env.current_obs()).clamp(-1, 1), auto_reset=False)
        done = env.done_persistent.clone()
        if bool(done.all()):
            break

    ok = (steps > 1).cpu().numpy()
    st = steps.cpu().numpy()
    per_step = np.zeros_like(st)
    per_step[ok] = vswitch.cpu().numpy()[ok] / (st[ok] - 1)
    coord = np.zeros_like(st)
    coord[ok] = flips.sum(-1).cpu().numpy()[ok] / (st[ok] - 1)
    dw = (torch.cat(dwells) if dwells else torch.zeros(1)).cpu().numpy()
    dt_ms = kw['dt'] * 1000
    swing = np.degrees(np.arctan(
        2 * math.pi * pool.amp_pool[idx].cpu().numpy()
        / pool.wavelen_pool[idx].cpu().numpy()))

    print(f'ckpt {a.ckpt}')
    print(f'control rate {1000/dt_ms:.0f} Hz   ({dt_ms:.0f} ms per command)')
    print(f'{int(ok.sum())} episodes, median length {np.median(st[ok]):.0f} steps\n')
    print(f'  vertex changes per step        : mean {per_step[ok].mean():.4f}   '
          f'median {np.median(per_step[ok]):.4f}')
    print(f'  coordinate sign flips per step : mean {coord[ok].mean():.4f} of 4')
    print(f'  steps held on one vertex       : mean {dw.mean():.2f}   '
          f'median {np.median(dw):.0f}   p90 {np.percentile(dw, 90):.0f}')
    print(f'  implied switching frequency    : '
          f'{per_step[ok].mean()*1000/dt_ms:.1f} Hz '
          f'against a {1000/dt_ms:.0f} Hz control rate')
    print(f'  steps with no change at all    : '
          f'{100*(1-per_step[ok]).clip(0, 1).mean():.1f}%')

    if swing_max > 0.0:
        print(f'\n{"bucket":<14s}{"n":>6s}{"switches/step":>15s}'
              f'{"implied Hz":>12s}{"median dwell":>14s}')
        for lo, hi, nm in [(1e-6, 10, 'swing 0-10'), (10, 20, 'swing 10-20'),
                           (20, 31, 'swing 20-30')]:
            sel = ok & (swing >= lo) & (swing < hi)
            if sel.sum() < 10:
                continue
            p = per_step[sel]
            print(f'{nm:<14s}{int(sel.sum()):>6d}{p.mean():>15.4f}'
                  f'{p.mean()*1000/dt_ms:>12.1f}'
                  f'{np.median(1.0/np.maximum(p, 1e-6)):>14.2f}')


if __name__ == '__main__':
    main()
